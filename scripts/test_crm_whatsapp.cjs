const assert = require('node:assert/strict');
const api = require('../assets/crm-whatsapp.js');
const artifact = require('../assets/crm-artifact.js');
const parse = (value) => value === '' || value === '-' || value == null ? null : Number(value);
const source = (row, category, audience, delivered, opened, clicked) => ({ __sourceRow: row, isoDate: '2026-10-27', Categoria: category, 'Público': audience, 'Total Entregue': delivered, Aberturas: opened, 'Total de cliques': clicked, Tema: 'Not copied', Mensagem: 'Not copied' });
const parent = source(20, 'Utilidade', 100, 90, 50, 20);
const child = source(21, '', 20, 18, 10, 3);
const records = api.recordsForGroup({ parent, children: [child] }, parse);
assert.deepEqual(Object.keys(records[0]).sort(), ['category', 'date', 'linked', 'parentRow', 'sourceRow', 'values'].sort(), 'No message, theme or contact data crosses the tracking contract');
assert.equal(records[1].category, 'Utilidade');
assert.equal(records[1].parentRow, 20);
assert.equal(records[1].linked, true);
let selected = api.select(records, '2026-10-27', '2026-10-27');
assert.equal(selected.metrics.Cliques.value, 20, 'Linked lines are never added to primary counts');
assert.equal(selected.groups[0].metrics.Publico.value, 100, 'Child audience must not replace the primary audience');
assert.equal(selected.records.length, 2, 'Linked evidence remains available');
const marketing = api.recordsForGroup({ parent: source(22, 'Marketing', 10, 9, 5, 1), children: [] }, parse);
const another = api.recordsForGroup({ parent: source(23, 'Marketing', 30, 20, 10, 2), children: [] }, parse);
selected = api.select([...records, ...marketing, ...another], '2026-10-27', '2026-10-27');
const group = selected.groups.find((item) => item.category === 'Marketing');
assert.equal(group.count, 2);
assert.equal(group.metrics.Publico.value, 40);
assert.equal(group.metrics.Cliques.value, 3);
assert.deepEqual(api.rates(Object.fromEntries(Object.entries(group.metrics).map(([key, metric]) => [key, metric.value]))), [29 / 40, 15 / 29, 3 / 15]);
const missing = api.recordsForGroup({ parent: source(24, 'Marketing', 30, '', 10, 0), children: [] }, parse);
assert.deepEqual(api.metric([...marketing, ...missing], 'Entregues'), { value: null, subtotal: 9, known: 1, expected: 2 });
assert.equal(api.metric(missing, 'Cliques').value, 0, 'Known zero remains zero');
assert.equal(api.metric([], 'Cliques').value, null, 'No records is not zero activity');
assert.deepEqual(api.rates({ Publico: 0, Entregues: 0, Aberturas: 0, Cliques: 0 }), [null, null, null]);
assert.equal(api.select(records, '2026-10-28', '2026-10-28').primary.length, 0);
global.localStorage = { getItem() { throw new Error('Sheet mode must not read local tracking'); } };
const html = artifact.tracking({ id: 'whatsapp-oficial' }, {}, { start: '2026-10-27', end: '2026-10-27', sheetRecords: records, sheetStatus: 'ready' });
assert.match(html, /data-tracking-origin="sheet"/);
assert.doesNotMatch(html, /data-artifact-track=|data-artifact-action="(?:import|reset)"/);
assert.match(html, /Vinculada a 20/);
assert.match(html, /Sem registro/);
assert.match(artifact.tracking({ id: 'whatsapp-oficial' }, {}, { start: '2026-10-27', end: '2026-10-27', sheetRecords: records, sheetStatus: 'error' }), /Leitura anterior da planilha preservada/);
delete global.localStorage;
console.log('WhatsApp sheet: parent/linked separation, category/date grouping, strict missingness, zero, rate denominators and read-only isolation passed.');
