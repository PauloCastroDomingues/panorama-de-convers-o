const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('C:/Users/reise/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const api = require('../assets/crm-sendflow.js');
const source = require('../data/ssot-commercial-channels.json');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const output = path.resolve(__dirname, '../output/crm-artifact-qa');
  fs.mkdirSync(output, { recursive: true });
  const errors = [], reports = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto((process.env.PANORAMA_URL || 'http://127.0.0.1:8021') + '/#crm', { waitUntil: 'domcontentloaded' });
    await page.locator('[data-crm-view="tracking"]').waitFor({ timeout: 45000 });
    await page.waitForFunction(() => !document.body.classList.contains('is-loading'), { timeout: 60000 });
    await page.waitForFunction(() => getComputedStyle(document.querySelector('#data-loader')).visibility === 'hidden');
    await page.waitForLoadState('networkidle');
    await page.evaluate(() => document.fonts.ready);
    const lastDate = api.availableDates(source, 'whatsapp-oficial').at(-1);
    assert.match(lastDate, /^\d{4}-\d{2}-\d{2}$/, 'Commercial SSOT must provide a latest date');
    const shiftDate = (value, days) => {
      const date = new Date(`${value}T12:00:00Z`);
      date.setUTCDate(date.getUTCDate() + days);
      return date.toISOString().slice(0, 10);
    };
    const previousDate = shiftDate(lastDate, -1), futureDate = shiftDate(lastDate, 1);
    const expected = api.commercial(source, 'whatsapp-oficial', lastDate, lastDate);
    const ticket = expected.ordersKnownDays === expected.expectedDays && expected.revenueKnownDays === expected.expectedDays && expected.orders > 0 && expected.revenue !== null ? expected.revenue / expected.orders : null;
    const integer = new Intl.NumberFormat('pt-BR', { maximumFractionDigits: 0 });
    const money = new Intl.NumberFormat('pt-BR', { style: 'currency', currency: 'BRL', maximumFractionDigits: 2 });
    const percent = new Intl.NumberFormat('pt-BR', { style: 'percent', minimumFractionDigits: 2, maximumFractionDigits: 2 });
    const expectedKpis = [[expected.sessions, integer], [expected.orders, integer], [expected.revenue, money], [expected.rate, percent], [ticket, money]]
      .map(([value, formatter]) => value === null ? 'Indisponivel' : formatter.format(value));
    assert.equal(await page.locator('#crm-date-start').inputValue(), lastDate, 'Default date follows commercial SSOT, not RD/operational dates');
    assert.equal(await page.locator('#crm-date-end').inputValue(), lastDate);
    assert.deepEqual(await page.locator('#crm-summary-kpis .kpi strong').allTextContents(), expectedKpis, 'Default KPIs exactly match the latest commercial SSOT totals');
    const selectDates = async (start, end) => {
      await page.locator('#crm-open-filters').click();
      await page.locator('#crm-date-start').fill(start);
      await page.locator('#crm-date-end').fill(end);
      await page.locator('#crm-apply-filters').click();
    };
    for (const id of ['whatsapp-oficial', 'email', 'whatsapp-organico']) {
      await page.locator(`[data-crm-tab="${id}"]`).click();
      assert.deepEqual(await page.locator('[data-crm-view]').evaluateAll((nodes) => nodes.map((node) => node.dataset.crmView)), ['conversion', 'pacing', 'activation', 'tracking']);
      assert.ok(await page.locator('[data-crm-view="conversion"] svg').isVisible(), `${id}: conversion funnel`);
      assert.equal(await page.locator('.crm-funnel-rate strong').innerText(), await page.locator('#crm-summary-kpis .kpi').nth(3).locator('strong').innerText(), `${id}: funnel retains the SSOT rate`);
      const funnelStyle = await page.locator('.crm-funnel-shape polygon').evaluate((node) => ({ fill: getComputedStyle(node).fill, opacity: Number(getComputedStyle(node).fillOpacity) }));
      assert.equal(funnelStyle.fill, 'rgb(251, 93, 6)', `${id}: Reise chart accent`);
      assert.ok(funnelStyle.opacity >= .1 && funnelStyle.opacity <= .25, `${id}: restrained brand fill with a visible outline`);
      await page.locator('[data-artifact-mode="plan"]').click();
      assert.equal(await page.locator('.crm-artifact-goals > div').count(), id === 'whatsapp-oficial' ? 8 : 5);
      assert.equal(await page.locator('.crm-artifact-daily thead th').count(), 8);
      assert.match(await page.locator('.crm-artifact-pacing').innerText(), /19\/10 a 25\/10\/2026/);
      for (const [name, width, height] of [['desktop', 1440, 1000], ['tablet', 820, 1180], ['mobile', 390, 844], ['small-mobile', 320, 740]]) {
        await page.setViewportSize({ width, height });
        await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${id}/${name}: page overflow`);
        assert.ok(await page.locator('.crm-funnel-rate').evaluate((node) => node.scrollWidth <= node.clientWidth && getComputedStyle(node).fontSize !== '0px'), `${id}/${name}: rate label fits`);
        await page.evaluate(() => scrollTo(0, 0));
        await page.screenshot({ path: path.join(output, `${id}-${name}-overview.png`) });
        await page.locator('[data-crm-view="conversion"]').screenshot({ path: path.join(output, `${id}-${name}-conversion.png`) });
        await page.locator('[data-crm-view="activation"]').screenshot({ path: path.join(output, `${id}-${name}-activation.png`) });
        await page.locator('[data-crm-view="pacing"]').screenshot({ path: path.join(output, `${id}-${name}-pacing.png`) });
        await page.locator('[data-crm-view="tracking"]').screenshot({ path: path.join(output, `${id}-${name}-tracking.png`) });
        reports.push(`${id}/${name}`);
      }
      await page.setViewportSize({ width: 1440, height: 1000 });
      await page.locator('[data-artifact-mode="actual"]').click();
    }
    await page.locator('[data-crm-tab="whatsapp-oficial"]').click();
    await page.locator('[data-tracking-source="local"]').click();
    const trackingRow = page.locator(`[data-tracking-id="${lastDate}:0"]`);
    const publicInput = trackingRow.locator('[data-artifact-track="Publico"]');
    await publicInput.pressSequentially('100', { delay: 30 });
    assert.equal(await publicInput.inputValue(), '100');
    assert.ok(await publicInput.evaluate((input) => document.activeElement === input), 'Typing must preserve focus');
    await trackingRow.locator('[data-artifact-track="Entregues"]').fill('0');
    assert.equal(await trackingRow.locator('[data-tracking-output="0"]').innerText(), '0,00%');
    await trackingRow.locator('[data-artifact-track="Cliques"]').fill('3');
    assert.equal(await page.locator('[data-tracking-total]').innerText(), '3');
    assert.equal(await page.locator(`[data-tracking-day-status="${lastDate}"]`).innerText(), '3 cliques');
    assert.equal(await page.locator('[data-tracking-coverage]').innerText(), '3/8 campos preenchidos');
    await trackingRow.locator('[data-artifact-track="Cliques"]').fill('0');
    assert.equal(await page.locator(`[data-tracking-day-status="${lastDate}"]`).innerText(), '0 cliques');
    await trackingRow.locator('[data-artifact-track="Cliques"]').fill('');
    assert.equal(await page.locator(`[data-tracking-day-status="${lastDate}"]`).innerText(), 'Parcial');
    await trackingRow.locator('[data-artifact-track="Cliques"]').fill('3');
    await selectDates(previousDate, previousDate);
    assert.equal(await page.locator('[data-artifact-track="Publico"]').first().inputValue(), '', 'Different dates cannot inherit entries');
    await selectDates(lastDate, lastDate);
    assert.equal(await publicInput.inputValue(), '100', 'Return to the same date restores entries');
    await selectDates(futureDate, futureDate);
    assert.equal(await page.locator('#crm-date-start').inputValue(), futureDate, 'Explicit dates are never shifted silently');
    assert.equal(await page.locator('#crm-date-end').inputValue(), futureDate);
    assert.equal(await page.locator('#crm-period-preset').inputValue(), 'custom', 'Future dates retain the custom period');
    assert.deepEqual(await page.locator('#crm-summary-kpis .kpi strong').allTextContents(), Array(5).fill('Indisponivel'), 'Dates after the snapshot cannot expose commercial results');
    assert.equal(await page.locator('#crm-summary-kpis').isVisible(), false);
    assert.equal(await page.locator('#crm-open-latest').isVisible(), true);
    await page.locator('#crm-open-latest').click();
    assert.equal(await page.locator('#crm-date-start').inputValue(), lastDate);
    assert.equal(await page.locator('#crm-date-end').inputValue(), lastDate);
    assert.deepEqual(await page.locator('#crm-summary-kpis .kpi strong').allTextContents(), expectedKpis, 'Returning to the latest date restores the exact SSOT totals');
    await page.locator('#crm-open-filters').click();
    await page.locator('#crm-period-preset').selectOption('previous-day');
    const yesterday = await page.evaluate(() => { const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Sao_Paulo' }).format(new Date()); const date = new Date(`${today}T12:00:00Z`); date.setUTCDate(date.getUTCDate() - 1); return date.toISOString().slice(0, 10); });
    assert.equal(await page.locator('#crm-date-start').inputValue(), yesterday, 'Previous day follows the real calendar, not the snapshot date');
    assert.equal(await page.locator('#crm-date-end').inputValue(), yesterday);
    await page.locator('#crm-cancel-filters').click();
    assert.equal(await page.locator('#crm-date-start').inputValue(), lastDate, 'Cancel preserves the applied dates');
    await selectDates('2026-10-19', '2026-10-25');
    assert.equal(await page.locator('.crm-tracking-table tbody [data-tracking-id]').count(), 2, 'Daily editor avoids rendering a week of blank inputs');
    assert.equal(await page.locator('[data-tracking-select]').count(), 7);
    await page.locator('[data-tracking-select="2026-10-20"]').click();
    assert.equal(await page.locator('[data-tracking-id]').first().getAttribute('data-tracking-id'), '2026-10-20:0');
    assert.ok(await page.locator('[data-tracking-select="2026-10-20"]').evaluate((node) => node === document.activeElement));
    await page.locator('[data-artifact-track="Publico"]').first().fill('200');
    await page.locator('[data-tracking-select="2026-10-21"]').click();
    assert.equal(await page.locator('[data-artifact-track="Publico"]').first().inputValue(), '');
    await page.locator('[data-tracking-select="2026-10-20"]').click();
    assert.equal(await page.locator('[data-artifact-track="Publico"]').first().inputValue(), '200');
    await page.locator('[data-tracking-mode="period"]').click();
    assert.equal(await page.locator('.crm-tracking-table tbody [data-tracking-id]').count(), 14);
    assert.equal(await page.locator('.crm-track-subtotal').count(), 7);
    assert.ok(await page.locator('.crm-tracking-scroll').evaluate((node) => node.clientHeight <= 420 && node.scrollHeight > node.clientHeight), 'Full table stays in a bounded viewport');
    assert.match(await page.locator('.crm-artifact-daily').innerText(), /Anterior 12\/10/);
    await page.locator('[data-artifact-mode="plan"]').click();
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: path.join(output, 'weekly-desktop.png'), fullPage: true });
    assert.equal(await page.locator('.crm-source-details').getAttribute('open'), null, 'Audit tables are collapsed initially');
    await selectDates(shiftDate(lastDate, -12), lastDate);
    await page.locator('[data-tracking-mode="day"]').click();
    await page.locator(`[data-tracking-select="${shiftDate(lastDate, -12)}"]`).click();
    for (const [name, width, height] of [['desktop', 1440, 1000], ['tablet', 820, 1180], ['mobile', 390, 844], ['small-mobile', 320, 740]]) {
      await page.setViewportSize({ width, height });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      await page.locator('[data-crm-view="tracking"]').screenshot({ path: path.join(output, `studio-tracking-${name}.png`) });
    }
    await page.locator('[data-tracking-mode="period"]').click();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile period table scrolls inside its container');
    await page.locator('[data-crm-view="tracking"]').screenshot({ path: path.join(output, 'studio-tracking-mobile-period.png') });
    await page.locator('[data-tracking-mode="day"]').click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('[data-artifact-page="acompanhamento"][data-step="1"]').click();
    assert.equal(await page.locator('[data-tracking-select]').count(), 6, 'Remaining six dates are reachable');
    assert.equal(await page.locator('[data-tracking-id]').first().getAttribute('data-tracking-id'), `${shiftDate(lastDate, -5)}:0`);
    await page.locator(`[data-tracking-select="${lastDate}"]`).click();
    assert.equal(await page.locator('[data-artifact-track="Cliques"]').first().inputValue(), '3', 'Paging preserves earlier edits');
    await page.locator(`[data-tracking-select="${previousDate}"]`).click();
    assert.equal(await page.locator('[data-artifact-track="Cliques"]').first().inputValue(), '');
    await page.locator('[data-crm-tab="all"]').click();
    assert.equal(await page.locator('#crm-detail tbody tr').count(), 3);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ status: 'passed', defaultDate: lastDate, futureDate, calendarPreviousDay: yesterday, expectedKpis, views: ['conversion', 'daily table/chart', 'activation', 'daily tracking'], reports, errors }));
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
