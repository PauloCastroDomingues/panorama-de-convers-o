const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({ console, Intl, Date, Map, Set, document: {querySelector: () => null} });
vm.runInContext(fs.readFileSync('assets/app.js', 'utf8'), context);
const run = code => vm.runInContext(code, context);
const range = (preset, today) => JSON.parse(JSON.stringify(run(`calendarPeriod('${preset}', '${today}')`)));
assert.deepEqual(range('today', '2026-11-04'), ['2026-11-04', '2026-11-04']);
assert.deepEqual(range('yesterday', '2026-11-04'), ['2026-11-03', '2026-11-03']);
assert.deepEqual(range('last-7', '2026-11-04'), ['2026-10-28', '2026-11-03']);
assert.deepEqual(range('last-30', '2026-11-04'), ['2026-10-05', '2026-11-03']);
assert.deepEqual(range('mtd', '2026-11-04'), ['2026-11-01', '2026-11-03']);
assert.equal(range('mtd', '2026-11-01'), null);
assert.deepEqual(range('last-month', '2026-01-05'), ['2025-12-01', '2025-12-31']);
assert.deepEqual(range('last-month', '2024-03-05'), ['2024-02-01', '2024-02-29']);
assert.equal(run("growthToday(new Date('2026-11-04T01:00:00Z'))"), '2026-11-03');
assert.equal(run("growthToday(new Date('2026-11-04T03:00:00Z'))"), '2026-11-04');
run("state.availableEnd='2026-10-29'; state.compareMode='previous'; applyPeriodPreset('current-day')");
assert.equal(run('state.start'), '2026-10-29');
assert.equal(run('state.compareEnd'), '2026-10-28');
run("applyPeriodPreset('month')");
assert.equal(run('state.start'), '2026-10-01');
assert.equal(run('state.end'), '2026-10-29');
console.log('Date presets passed: Sao Paulo, D-1, month/year boundaries, leap year and preserved data-relative presets.');
