const assert = require('node:assert/strict');
const funnel = require('../assets/crm-funnel.js');
const reference = require('../data/crm-weekly-reference.json');
const ref = reference.channels.find(c => c.id === 'whatsapp-oficial');
const options = { start: '2026-10-28', end: '2026-10-28', referencePeriod: reference.period, compareEnabled: true };
const stages = [ { label: 'Publico', value: 100 }, { label: 'Entregues', value: 90 }, { label: 'Leitura', value: 45 }, { label: 'Cliques', value: 9 } ];
const channel = { id: ref.id, name: ref.name, metrics: [ { key: 'sessions', actual: 554, comparison: 945 }, { key: 'orders', actual: 17, comparison: 9 }, { key: 'rate', actual: 17 / 554 } ],
  activation: { segments: [ { name: 'Marketing', shots: 2, stages }, { name: 'Utilidade', shots: 1, stages } ] } };
const before = JSON.stringify({ channel, ref });
const actual = funnel.model(channel, ref, options);
assert.equal(actual.segments[0].stages[2].rate, .5);
assert.equal(actual.commercial[0].value, 554);
assert.equal(actual.commercial[1].value, 17);
assert.equal(actual.rate, 17 / 554);
const html = funnel.render(channel, ref, options);
assert.equal((html.match(/data-funnel-stage=/g) || []).length, 8);
assert.equal((html.match(/data-funnel-commercial="sessions"/g) || []).length, 1, 'Never repeat the channel result in each template');
assert.match(html, /Sem atribuicao por tipo de disparo/);
assert.equal((html.match(/data-funnel-band=/g) || []).length, 10, 'Four visual slices per template and two shared commercial slices');
assert.equal((html.match(/<polygon /g) || []).length, 10, 'Keep the funnel silhouette instead of cards');
assert.doesNotMatch(funnel.render(channel, ref, { ...options, compareEnabled: false }), /Anterior:|performance-delta/);
const plan = funnel.model(channel, ref, { ...options, activationMode: 'plan' });
assert.equal(plan.commercial[0].value, 3605);
assert.equal(plan.commercial[1].value, 119);
assert.equal(plan.segments[0].stages[0].value, 4466);
assert.doesNotMatch(funnel.render(channel, ref, { ...options, activationMode: 'plan' }), /estimados como sessoes|performance-delta/);
const partial = structuredClone(channel);
partial.activation.segments[0].stages[1].complete = false;
assert.equal(funnel.model(partial, ref, options).segments[0].stages[2].rate, null);
partial.activation.segments[0].stages[1] = { label: 'Entregues', value: 0 };
assert.equal(funnel.model(partial, ref, options).segments[0].stages[1].rate, 0);
assert.equal(funnel.model(partial, ref, options).segments[0].stages[2].rate, null);
const organic = reference.channels.find(c => c.id === 'whatsapp-organico');
assert.equal(funnel.model({ ...channel, id: organic.id }, organic, { ...options, activationMode: 'plan' }).segments[0].stages[2].denominator, 'Membros');
assert.match(funnel.render({ ...channel, id: organic.id }, organic, { ...options, activationMode: 'plan' }), /4\.093/);
const rd = { ...channel, rd: { current: { records: [{}], countIssues: 1, receivedTotals: { selected: 100, delivered: 0, opened: 20, clicked: 3 }, consolidated: null } } };
assert.equal(funnel.model(rd, ref, options).segments[0].stages[2].rate, null);
const empty = { ...channel, activation: { segments: [] } };
assert.match(funnel.render(empty, ref, options), /554/);
assert.equal(JSON.stringify({ channel, ref }), before, 'Read-only models');
console.log('CRM funnels: stages, shared SSOT totals, plans, comparisons, coverage and immutability OK.');
