const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/reise/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const adapter = require('../assets/crm-sendflow.js');
const snapshot = require('../data/crm-sendflow-snapshot.json');
const ssotSnapshot = require('../data/ssot-commercial-channels.json');
const root = path.resolve(__dirname, '..');

(async () => {
  const output = path.join(root, 'output', 'sendflow-qa');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const errors = [], reports = [];
  try {
    const context = await browser.newContext();
    const page = await context.newPage();
    page.on('pageerror', (error) => errors.push(error.message));
    const started = Date.now();
    await page.goto('http://127.0.0.1:8020/?crmChannel=whatsapp-organico#crm', { waitUntil: 'domcontentloaded' });
    await page.locator('.crm-sendflow-kpis strong').first().waitFor({ timeout: 25000 });
    await page.waitForFunction(() => !document.body.classList.contains('is-loading'), { timeout: 25000 });
    assert.deepEqual(await page.locator('.crm-sendflow-kpis strong').allTextContents(), ['90', '197', '514.861', '726']);
    assert.equal(await page.locator('.crm-sendflow-actions tbody tr').count(), 12);
    await page.locator('[data-sendflow-page="1"]').click();
    assert.match(await page.locator('.crm-sendflow-pagination').innerText(), /Pagina 2 de 8/);
    await page.locator('[data-sendflow-sort="read"]').click();
    const sorted = await page.locator('.crm-sendflow-actions tbody tr td:nth-child(5)').allTextContents();
    assert.ok(Number(sorted[0].replace(/\./g, '')) >= Number(sorted[1].replace(/\./g, '')));
    for (const [name, width, height] of [['desktop', 1440, 1000], ['tablet', 820, 1180], ['mobile', 390, 844]]) {
      await page.setViewportSize({ width, height });
      await page.locator('.crm-sendflow-report').scrollIntoViewIfNeeded();
      const overflow = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }));
      assert.ok(overflow.document <= overflow.viewport + 1, `${name}: page overflow ${JSON.stringify(overflow)}`);
      await page.screenshot({ path: path.join(output, `${name}.png`) });
      const box = await page.locator('.crm-sendflow-kpis').boundingBox();
      assert.ok(box.width > 200 && box.height > 60, `${name}: report is visible`);
      reports.push({ name, width, overflow, kpis: await page.locator('.crm-sendflow-kpis strong').allTextContents() });
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#crm-open-filters').click();
    await page.locator('#crm-date-start').fill('2026-09-15');
    await page.locator('#crm-date-end').fill('2026-09-21');
    await page.locator('#crm-apply-filters').click();
    const expected = adapter.summarize(snapshot, '2026-09-15', '2026-09-21');
    assert.equal(await page.locator('.crm-sendflow-kpis strong').first().innerText(), String(expected.actions));
    assert.match(await page.locator('#crm-filter-summary-comparison').innerText(), /08\/09\/2026 a 14\/09\/2026/);
    assert.equal(await page.locator('.crm-sendflow-bars i.comparison').count(), 7);
    for (const id of ['email', 'whatsapp-oficial']) {
      await page.locator(`#crm-channel-tabs [data-crm-tab="${id}"]`).click();
      const expectedCommercial = adapter.commercial(ssotSnapshot, id, '2026-09-15', '2026-09-21');
      assert.ok(expectedCommercial.orders !== null);
      assert.equal(await page.locator('#crm-summary-kpis .kpi strong').nth(1).innerText(), new Intl.NumberFormat('pt-BR').format(expectedCommercial.orders));
      assert.equal(await page.locator('#crm-ssot-reconciliation').isVisible(), true);
    }
    await page.locator('#crm-channel-tabs [data-crm-tab="whatsapp-organico"]').click();
    await page.locator('#crm-open-filters').click();
    await page.locator('#crm-date-start').fill('2026-08-01');
    await page.locator('#crm-date-end').fill('2026-08-31');
    await page.locator('#crm-cancel-filters').click();
    assert.equal(await page.locator('.crm-sendflow-kpis strong').first().innerText(), String(expected.actions));
    await page.locator('#crm-open-filters').click();
    await page.locator('#crm-date-start').fill('2026-08-01');
    await page.locator('#crm-date-end').fill('2026-08-31');
    await page.locator('#crm-apply-filters').click();
    assert.equal(await page.locator('.crm-sendflow-kpis strong').first().innerText(), 'Nao informado');
    assert.match(await page.locator('.crm-sendflow-warning').innerText(), /nao esta coberto/);
    const august = adapter.commercial(ssotSnapshot, 'whatsapp-organico', '2026-08-01', '2026-08-31');
    assert.equal(await page.locator('#crm-summary-kpis .kpi strong').nth(1).innerText(), new Intl.NumberFormat('pt-BR').format(august.orders), 'SSOT orders remain visible outside SendFlow coverage');
    const noProviderContext = await browser.newContext();
    const noProvider = await noProviderContext.newPage();
    noProvider.on('pageerror', (error) => errors.push(error.message));
    await noProvider.route('**/data/crm-sendflow-snapshot.json', (route) => route.fulfill({ status: 503, body: '' }));
    await noProvider.goto('http://127.0.0.1:8020/#crm', { waitUntil: 'domcontentloaded' });
    await noProvider.locator('#crm-open-filters').waitFor();
    await noProvider.waitForFunction(() => !document.querySelector('#crm-open-filters').disabled, { timeout: 20000 });
    await noProvider.locator('#crm-open-filters').click();
    await noProvider.locator('#crm-channel-filter').selectOption('whatsapp-organico');
    await noProvider.locator('#crm-date-start').fill('2026-09-15');
    await noProvider.locator('#crm-date-end').fill('2026-09-21');
    await noProvider.locator('#crm-apply-filters').click();
    const noProviderExpected = adapter.commercial(ssotSnapshot, 'whatsapp-organico', '2026-09-15', '2026-09-21');
    assert.equal(await noProvider.locator('#crm-summary-kpis .kpi strong').nth(1).innerText(), new Intl.NumberFormat('pt-BR').format(noProviderExpected.orders));
    assert.equal(await noProvider.locator('.crm-activation-summary').count(), 0, 'No provider must not create a zero-valued activation funnel');
    await noProviderContext.close();
    const bridgedContext = await browser.newContext();
    const bridgedPage = await bridgedContext.newPage();
    bridgedPage.on('pageerror', (error) => errors.push(error.message));
    await bridgedPage.route('**/data/crm-sendflow-config.json', (route) => route.fulfill({ json: { endpoint: '/api/crm-sendflow' } }));
    let available = true;
    await bridgedPage.route('**/api/crm-sendflow', (route) => route.fulfill(available ? { json: { ...snapshot, source: { ...snapshot.source, mode: 'live_sheet' } } } : { status: 503, json: { ok: false } }));
    await bridgedPage.goto('http://127.0.0.1:8020/?crmChannel=whatsapp-organico#crm', { waitUntil: 'domcontentloaded' });
    await bridgedPage.locator('.crm-sendflow-source .status-pill').filter({ hasText: 'Leitura da planilha' }).waitFor({ timeout: 20000 });
    available = false;
    await bridgedPage.reload({ waitUntil: 'domcontentloaded' });
    await bridgedPage.locator('.crm-sendflow-source .status-pill').filter({ hasText: 'Ultima leitura em cache' }).waitFor({ timeout: 20000 });
    assert.equal(await bridgedPage.locator('.crm-sendflow-kpis strong').first().innerText(), '90');
    await bridgedContext.close();
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log(JSON.stringify({ status: 'passed', elapsedMs: Date.now() - started, reports, errors, comparisons: 'matched date offsets, cancel isolation and no fabricated zeros outside coverage', ssotCross: 'email and both WhatsApp channels use SSOT; orders survive missing provider and missing SendFlow date coverage', bridgeHarness: 'last validated sheet response survives an upstream outage; not a live Apps Script deployment test' }, null, 2));
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
