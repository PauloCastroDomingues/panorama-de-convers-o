const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('C:/Users/reise/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const rd = require('../assets/crm-rd.js');
const ssot = require('../assets/crm-sendflow.js');
const pilot = rd.normalizeSnapshot(require('../data/crm-rd-snapshot.json'));
const commercialSnapshot = require('../data/ssot-commercial-channels.json');
const baseUrl = process.env.PANORAMA_URL || 'http://127.0.0.1:8020';

(async () => {
  const output = path.resolve(__dirname, '../output/rd-qa');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const errors = [], reports = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(baseUrl + '/?crmChannel=email#crm', { waitUntil: 'domcontentloaded' });
    await page.locator('.crm-rd-report').waitFor({ timeout: 25000 });
    await page.waitForFunction(() => !document.body.classList.contains('is-loading'), { timeout: 25000 });
    await page.waitForFunction(() => getComputedStyle(document.querySelector('#data-loader')).visibility === 'hidden');
    await page.evaluate(() => document.fonts.ready);
    const full = rd.selectPeriod(pilot, pilot.period.start, pilot.period.end);
    assert.deepEqual(await page.locator('.crm-rd-report .kpi strong').allTextContents(), [String(pilot.records.length), String(pilot.records.length - pilot.countIssueRows), String(pilot.countIssueRows), new Intl.NumberFormat('pt-BR').format(full.receivedTotals.clicked)]);
    assert.equal(await page.locator('.crm-rd-table tbody tr').count(), 10);
    assert.match(await page.locator('.crm-rd-comparison').innerText(), /Sem extracao RD validada/);
    assert.ok((await page.locator('#crm-filter-summary-period').innerText()).includes(`${pilot.period.start.split('-').reverse().join('/')} a ${pilot.period.end.split('-').reverse().join('/')}`));
    for (const [name, width, height] of [['desktop', 1440, 1000], ['tablet', 820, 1180], ['mobile', 390, 844]]) {
      await page.setViewportSize({ width, height });
      await page.locator('.crm-rd-report').scrollIntoViewIfNeeded();
      const dimensions = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }));
      assert.ok(dimensions.document <= width + 1, `${name}: page overflow`);
      assert.ok(await page.locator('.crm-rd-table td:first-child strong').evaluateAll((nodes) => nodes.every((node) => node.scrollWidth <= node.clientWidth + 1)), `${name}: campaign names must not overlap adjacent cells`);
      await page.locator('.crm-rd-report').screenshot({ path: path.join(output, `${name}.png`) });
      reports.push({ name, width, dimensions });
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#crm-rd-quality').selectOption('review');
    const reviewed = pilot.records.filter((row) => row.countIssues.length).sort((a, b) => b.sentAt.localeCompare(a.sentAt)).slice(0, 10);
    assert.equal(await page.locator('.crm-rd-table tbody tr').count(), reviewed.length);
    const reviewIds = await page.locator('.crm-rd-table tbody tr').evaluateAll((rows) => rows.map((row) => row.dataset.rdId).sort());
    assert.deepEqual(reviewIds, reviewed.map((row) => row.campaignId).sort());
    assert.equal(await page.locator('.crm-rd-table .rd-review').count(), reviewed.length * 3);
    assert.deepEqual(await page.locator('.crm-rd-table tbody tr td:nth-child(4)').allTextContents(), reviewed.map((row) => new Intl.NumberFormat('pt-BR').format(row.counts.delivered)));
    await page.locator('#crm-rd-quality').selectOption('all');
    await page.locator('#crm-rd-search').pressSequentially('ultimas 07', { delay: 20 });
    assert.equal(await page.locator('.crm-rd-table tbody tr').count(), 1);
    assert.equal(await page.locator('.crm-rd-table tbody tr').getAttribute('data-rd-id'), '20428712');
    const controlRate = pilot.records.find((row) => row.campaignId === '20428712').provisionalRates.clickToOpenRate;
    assert.equal(await page.locator('.crm-rd-table tbody tr td:nth-child(9)').innerText(), new Intl.NumberFormat('pt-BR', { style: 'percent', minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(controlRate));
    assert.equal(await page.evaluate(() => document.activeElement.id), 'crm-rd-search', 'Table filtering must not drop input focus');
    await page.locator('#crm-rd-search').fill('');
    await page.locator('[data-rd-sort="clicked"]').click();
    const top = pilot.records.slice().sort((a, b) => b.counts.clicked - a.counts.clicked)[0];
    assert.equal(await page.locator('.crm-rd-table tbody tr').first().getAttribute('data-rd-id'), top.campaignId);
    await page.locator('[data-rd-page="1"]').click();
    assert.ok((await page.locator('#crm-rd-table-root .crm-sendflow-pagination').innerText()).includes(`Pagina 2 de ${Math.ceil(pilot.records.length / 10)}`));
    await page.locator('#crm-open-filters').click();
    await page.locator('#crm-date-start').fill('2026-10-23');
    await page.locator('#crm-date-end').fill('2026-10-24');
    await page.locator('#crm-apply-filters').click();
    assert.equal(await page.locator('.crm-rd-report .kpi strong').first().innerText(), String(rd.selectPeriod(pilot, '2026-10-23', '2026-10-24').records.length));
    assert.match(await page.locator('.crm-rd-comparison').innerText(), /Comparativo observado/);
    await page.locator('#crm-open-filters').click();
    await page.locator('#crm-date-start').fill('2026-09-15');
    await page.locator('#crm-date-end').fill('2026-09-21');
    await page.locator('#crm-apply-filters').click();
    assert.match(await page.locator('.crm-rd-report .crm-sendflow-warning').innerText(), /nao possui registros nesta extracao/);
    assert.equal(await page.locator('.crm-rd-report .kpi strong').last().innerText(), 'Sem coleta');
    const expected = ssot.commercial(commercialSnapshot, 'email', '2026-09-15', '2026-09-21');
    assert.equal(await page.locator('#crm-summary-kpis .kpi strong').nth(1).innerText(), new Intl.NumberFormat('pt-BR').format(expected.orders));
    const missing = await browser.newPage();
    missing.on('pageerror', (error) => errors.push(error.message));
    await missing.route('**/data/crm-rd-snapshot.json', (route) => route.fulfill({ status: 503, body: '' }));
    await missing.goto(baseUrl + '/#crm', { waitUntil: 'domcontentloaded' });
    await missing.waitForFunction(() => !document.querySelector('#crm-open-filters').disabled, { timeout: 25000 });
    await missing.locator('#crm-open-filters').click();
    await missing.locator('#crm-channel-filter').selectOption('email');
    await missing.locator('#crm-date-start').fill('2026-09-15');
    await missing.locator('#crm-date-end').fill('2026-09-21');
    await missing.locator('#crm-apply-filters').click();
    assert.equal(await missing.locator('#crm-summary-kpis .kpi strong').nth(1).innerText(), new Intl.NumberFormat('pt-BR').format(expected.orders));
    assert.equal(await missing.locator('.crm-rd-report').count(), 0);
    assert.match(await missing.locator('#crm-validation-banner').innerText(), /Snapshot RD: HTTP 503/);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ status: 'passed', reports, errors, realCollection: `${pilot.records.length} campaigns, ${pilot.countIssueRows} flagged; provisional rates only`, controls: 'accent-insensitive search, focus retention, sorting, quality filter, pagination and date comparisons', sourceIsolation: 'missing RD data never removes SSOT commercial results' }, null, 2));
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
